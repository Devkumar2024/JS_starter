// prompt takes value in string format, we have to explicitly typecast
let number1 = Number(prompt("Enter 1st number : "));
let number2 = Number(prompt("Enter 2nd number : "));


console.log("n1 + n2 = ", number1 + number2);
console.log("n1 - n2 = ", number1 - number2);
console.log("n1 * n2 = ", number1 * number2);
console.log("n1 / n2 = ", number1 / number2);
console.log("n1 ** n2 = ", number1 ** number2);
